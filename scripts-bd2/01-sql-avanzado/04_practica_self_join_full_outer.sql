-- Contexto: Empleado y gerente con sus departamentos (self join) y FULL OUTER JOIN.

SELECT E.FIRST_NAME as Empleado,
    E.LAST_NAME as apellido, 
    M.FIRST_NAME as gerente,
   M.LAST_NAME as apellido,
    D.DEPARTMENT_NAME as depEmpleado,
    DM.DEPARTMENT_NAME as depGerente
FROM HR.employees E
INNER JOIN HR.EMPLOYEES M
ON E.MANAGER_ID = m.employee_id
INNER JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
INNER JOIN HR.DEPARTMENTS DM
    ON M.DEPARTMENT_ID = DM.DEPARTMENT_ID
    
SELECT E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME
FROM HR.EMPLOYEES E
FULL OUTER JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;