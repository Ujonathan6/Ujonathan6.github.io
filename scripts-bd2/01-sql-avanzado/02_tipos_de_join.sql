--Self Join

SELECT E.FIRST_NAME || '' || E.LAST_NAME AS NOMBREE ,
    M.FIRST_NAME || '' || M.LAST_NAME AS NOMBREM
FROM HR.EMPLOYEES E
LEFT JOIN HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;


--producto cartesiano
SELECT E.FIRST_NAME,
    D.DEPARTMENT_NAME
