--LEFT JOIN EXCLUSIVO (SOLO TRAE AL QUE NO ESTE RELACIONADO CON LA OTRA TABLA)
    
SELECT E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.LAST_NAME , 
    D.DEPARTMENT_NAME
FROM HR.EMPLOYEES E
    LEFT JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
