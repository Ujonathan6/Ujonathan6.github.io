-- Contexto: Practica de INNER y LEFT JOIN entre empleados, departamentos, trabajos y ubicaciones.

SELECT E.FIRST_NAME,
    E.LAST_NAME,
    E.SALARY,
    D.DEPARTMENT_NAME 
    FROM HR.EMPLOYEES E
    INNER JOIN HR.DEPARTMENTS D
    ON D.DEPARTMENT_ID =  E.DEPARTMENT_ID;
    
    
