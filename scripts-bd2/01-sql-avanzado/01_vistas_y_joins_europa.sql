-- Contexto: Copias de tablas HR, vista de empleados y vista de empleados europeos (JOIN de 5 tablas).

SELECT * FROM HR.departments

SELECT * FROM HR.COUNTRIES

SELECT * FROM HR.LOCATIONS

SELECT * FROM HR.EMPLOYEES

SELECT * FROM HR.JOBS

CREATE TABLE EMPLEADO 
AS SELECT * 
FROM HR.EMPLOYEES;

CREATE TABLE DEPARTAMENTOS
AS SELECT *
FROM HR.DEPARTMENTS


CREATE TABLE LOCACIONES
AS SELECT *
FROM HR.LOCATIONS



CREATE TABLE CONTINENTES
AS SELECT *
FROM HR.COUNTRIES


CREATE TABLE REGIONES
AS SELECT *
FROM HR.REGIONS

CREATE OR REPLACE VIEW VW_EMPLEADO
AS
SELECT first_name AS NOMBRE_EMPLEADO,
        hire_date AS FECHA_CONTRATACION,
        salary AS SALARIO,
        EMAIL AS CORREO
FROM EMPLEADO
WHERE department_id in (80,90,100)

SELECT * 
FROM VW_EMPLEADO

CREATE OR REPLACE VIEW VW_EUROPEOS
AS
SELECT E.FIRST_NAME,
       E.LAST_NAME,
       E.SALARY,
       C.COUNTRY_NAME
FROM EMPLEADO E
JOIN DEPARTAMENTOS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN LOCACIONES L
ON D.LOCATION_ID = L.LOCATION_ID
JOIN CONTINENTES C
ON L.COUNTRY_ID = C.COUNTRY_ID
JOIN REGIONES R
ON C.REGION_ID = R.REGION_ID
WHERE R.REGION_NAME = 'Europe';

SELECT * 
FROM VW_EUROPEOS
